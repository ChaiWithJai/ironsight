/**
 * Atlas order, declared EXPLICITLY and starting with the blank.
 *
 * Not `Object.keys(GLYPHS)`: JavaScript orders integer-like keys first and in
 * ascending numeric order regardless of how the object literal was written, so
 * '0' would take atlas slot 0 — and slot 0 is the sentinel the panel's shader
 * treats as "empty cell". The symptom is that every zero in the readout silently
 * vanishes, which reads as a formatting bug rather than a font bug and costs an
 * hour. The blank owns slot 0 here, on purpose.
 */
export const GLYPH_ORDER: readonly string[] = [
  ' ',
  ...'ABCDEFGHIJKLMNOPQRSTUVWXYZ',
  ...'0123456789',
  ...'.,-+:/%[]()#*=<>!_',
];
